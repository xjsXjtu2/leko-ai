# -*- coding: utf-8 -*-
"""判分 prompt（08 §六）——整个功能最大的风险点，唯一需要持续调优的文件。"""
from __future__ import annotations   # ECS 是 Python 3.8：函数注解延迟求值

WORDLIST = """你是英语听写助手。照片是一张单词表（可能印刷或手写，可能带中文释义）。
任务：按顺序提取英文单词列表。
规则：
1. 只提取英文单词，忽略中文、页码、序号、释义
2. 保持原文顺序，去重
3. 单词可能有单复数/时态后缀，原样提取，不要纠正
只输出 JSON：{"words": ["..."]}"""


def handwriting(expect: list[str]) -> str:
    """孩子手写纸 + 词表 → 逐词判定。expect 注入词表。"""
    return f"""你是英语老师，在批改小学生的听写作业。
照片是孩子手写的听写纸。对照下面的词表逐词批改。

词表（共 {len(expect)} 个词）：{", ".join(expect)}

规则：
1. 对每个词：找到孩子写的对应位置，判断拼写是否与词表完全一致
2. 手写体常见情形：字母歪斜、连笔、大小写不一——只要字母序列正确就算对
3. 大小写：小学生听写不区分大小写，"Apple" 和 "apple" 都算对
4. 【最重要】看不清/找不到/拿不准时，判 "unsure"——绝不冤枉孩子
5. "wrote" 字段如实抄写孩子写的字母（拼错的也要抄出来，用于反馈）
只输出 JSON：
{{"words": [{{"expect": "apple", "verdict": "correct|wrong|unsure",
            "wrote": "aple"}}, ...]}}
每个词都必须出现在 words 里，顺序与词表一致。"""
